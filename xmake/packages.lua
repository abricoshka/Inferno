package("keycodemapdb")
	set_kind("binary")
	set_homepage("https://gitlab.com/qemu-project/keycodemapdb")
	set_description("Keycode map database and generator")
	add_urls("https://gitlab.com/qemu-project/keycodemapdb.git")
	add_versions("2023.02.28", "f5772a62ec52591ff6870b7e8ef32482371f22c6")
	on_install(function (package)
		os.cp("tools", package:installdir())
		os.cp("data", package:installdir())
	end)
	on_test(function (package)
		assert(os.isfile(path.join(package:installdir(), "tools", "keymap-gen")))
		assert(os.isfile(path.join(package:installdir(), "data", "keymaps.csv")))
	end)
package_end()

package("mlib")
