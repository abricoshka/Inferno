	set_homepage("https://github.com/P-p-H-d/mlib")
	set_description("Generic type-safe containers for C99/C11")
	add_urls("https://github.com/P-p-H-d/mlib.git")
	add_versions("2026.07.22", "4acdfe4c12040150e2e531517a005a1aace6b794")
	on_install(function (package)
