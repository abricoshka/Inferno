	end)
package_end()

package("libyuv")
	set_homepage("https://chromium.googlesource.com/libyuv/libyuv/")
	set_description("YUV scaling and conversion library")
	add_urls("https://chromium.googlesource.com/libyuv/libyuv.git")
	add_versions("2026.09.04", "af1aaca84027a69ab25f251ade1bf1714b180d89")
	add_deps("cmake")
	on_load(function (package)
		package:add("links", "yuv")
		package:add("syslinks", package:is_plat("macosx") and "c++" or "stdc++")
	end)
	on_install("macosx", "linux", function (package)
		import("package.tools.cmake").install(package, {
			"-DCMAKE_BUILD_TYPE=" .. (package:is_debug() and "Debug" or "Release"),
			"-DBUILD_SHARED_LIBS=OFF",
			"-DLIBYUV_DISABLE_JPEG=ON",
		})
		os.tryrm(path.join(package:installdir("lib"), "*.dylib"))
		os.tryrm(path.join(package:installdir("lib"), "*.so*"))
		os.tryrm(package:installdir("bin"))
	end)
	on_test(function (package)
		assert(package:has_cfuncs("ARGBScale", {includes = "libyuv.h"}))
	end)
package_end()
